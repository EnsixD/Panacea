// Таблица тем — одна на всю систему.
//
// Лежит отдельным файлом, потому что читателей у неё двое и они в разных
// процессах: сама оболочка и экран блокировки. Тот запускается отдельно,
// до настроек пилюли не дотягивается и читает settings.json сам — а без
// общей таблицы ему пришлось бы держать свою копию цветов, и та разошлась
// бы с оболочкой на первой же правке.
//
// Темы не зависят от обоев: цвет задаёт выбранная тема, а не картинка на
// столе. Тема «default» — то, что было изначально: фон чёрный, а текст и
// акцент берутся из настроек, поэтому вручную выбранные цвета никуда не
// деваются.

