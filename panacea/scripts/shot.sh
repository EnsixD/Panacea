#!/bin/bash
# Скриншот области по стоп-кадру. Super+Shift+S.
#
# Раньше здесь было `grim -g "$(slurp)" - | wl-copy`: выделение шло по живому
# экрану. Снять то, что закрывается от первого движения мыши — открытое меню,
# всплывающую подсказку, список автодополнения — так нельзя: пока тянешь
# рамку, снимать уже нечего.
#
# Поэтому сначала снимок всего экрана, потом он показывается слоем оболочки
# поверх всего (ipc freeze), и только по нему идёт выделение.
#
# Область вырезается из этого же файла, а не снимается вторым вызовом grim с
# замершего экрана: второй снимок опять прошёл бы через композитор, и цвета
# зависели бы от того, что тот делает с выводом — ночная температура,
# насыщенность, дизеринг. Режем исходный кадр — он попадает в буфер ровно
# таким, каким был снят.
#
# Снимок хранится в PPM: его читают только слой стоп-кадра и обрезка, оба
# сразу, — жать и разжимать PNG ради временного файла незачем, а слой ещё и
# появляется заметно быстрее.
#
# Если оболочка не отвечает — выделение идёт по живому экрану, как раньше.
# Остаться без стоп-кадра лучше, чем без скриншота.

set -u

CFG="$HOME/.config/panacea"
DIR="${XDG_PICTURES_DIR:-$HOME/Pictures}/Screenshots"
SHOT=""
FROZEN=0

ipc() { qs -c "$CFG" ipc call pill "$@" >/dev/null 2>&1; }

# Снять слой обязательно: иначе при отмене или падении на экране навсегда
# останется висеть картинка, неотличимая от зависшего компьютера.
cleanup() {
    [ "$FROZEN" = 1 ] && ipc unfreeze
    [ -n "$SHOT" ] && rm -f -- "$SHOT"
}
trap cleanup EXIT INT TERM HUP

# Кадр целиком временный и большой (6 МБ на 1080p), поэтому в память, а не на
# диск: XDG_RUNTIME_DIR — tmpfs, и файл всё равно живёт до конца выделения.
SHOT=$(mktemp -p "${XDG_RUNTIME_DIR:-/tmp}" panacea-shot.XXXXXXXX.ppm) || exit 1

SNAP=0
if grim -t ppm "$SHOT" 2>/dev/null; then SNAP=1; fi

if [ "$SNAP" = 1 ] && ipc freeze "$SHOT"; then
    FROZEN=1
    # Слою нужен кадр, чтобы появиться на экране. Без паузы первые миллисекунды
    # выделения идут по живому экрану — ровно то, от чего уходили.
    sleep 0.08
fi

# Отмена по Esc или правой кнопкой — пустой вывод и ненулевой код.
GEOM=$(slurp -b 00000060 -c ffffffff -w 1) || exit 0
[ -n "$GEOM" ] || exit 0

# Стоп-кадр больше не нужен: обрезка идёт по файлу, и держать картинку на
# экране до конца — значит показывать её лишние доли секунды после клика.
if [ "$FROZEN" = 1 ]; then ipc unfreeze; FROZEN=0; fi

mkdir -p "$DIR" || exit 1
OUT="$DIR/$(date +'Screenshot_%Y-%m-%d_%H-%M-%S').png"

if [ "$SNAP" = 1 ]; then
    # Обычный путь: режем уже снятый кадр.
    python3 "$CFG/scripts/shotcrop.py" "$SHOT" "$GEOM" "$OUT" || exit 1
else
    # Кадра нет — снимаем область прямо сейчас, по живому экрану.
    grim -g "$GEOM" "$OUT" || exit 1
fi

# В буфер из файла, а не из потока: так код возврата принадлежит обрезке, а не
# wl-copy, которому пустой ввод сошёл бы за успешную работу.
wl-copy -t image/png < "$OUT"
ipc shotCopied "$OUT"
