#!/bin/bash
# Скриншот области по стоп-кадру. Super+Shift+S.
#
# Раньше здесь было `grim -g "$(slurp)" - | wl-copy`: выделение шло по живому
# экрану. Снять то, что закрывается от первого движения мыши — открытое меню,
# всплывающую подсказку, список автодополнения — так нельзя: пока тянешь
# рамку, снимать уже нечего.
#
# Поэтому сначала снимок всего экрана, потом он показывается слоем оболочки
# поверх всего (ipc freeze), и только по нему идёт выделение. Итоговый кадр
# снимается grim'ом с этого замершего слоя — обрезать исходный файл нечем и
# не нужно: ImageMagick в системе нет, а тянуть его ради одной обрезки незачем.
#
# Если оболочка не отвечает — выделение идёт по живому экрану, как раньше.
# Остаться без стоп-кадра лучше, чем без скриншота.

set -u

CFG="$HOME/.config/panacea"
SHOT=""
FROZEN=0

ipc() { qs -c "$CFG" ipc call pill "$@" >/dev/null 2>&1; }

# Снять слой обязательно: иначе при отмене или падении на экране навсегда
# останется висеть картинка, неотличимая от зависшего компьютера.
cleanup() {
    [ "$FROZEN" = 1 ] && ipc unfreeze
    [ -n "$SHOT" ] && rm -f -- "$SHOT"
}
trap cleanup EXIT INT TERM HUP

SHOT=$(mktemp -t panacea-shot.XXXXXXXX.png) || exit 1

if grim "$SHOT" 2>/dev/null && ipc freeze "$SHOT"; then
    FROZEN=1
    # Слою нужен кадр, чтобы появиться на экране. Без паузы первые миллисекунды
    # выделения идут по живому экрану — ровно то, от чего уходили.
    sleep 0.08
fi

# Отмена по Esc или правой кнопкой — пустой вывод и ненулевой код.
GEOM=$(slurp -b 00000060 -c ffffffff -w 1) || exit 0
[ -n "$GEOM" ] || exit 0

if grim -g "$GEOM" - | wl-copy -t image/png; then
    ipc shotCopied
fi
